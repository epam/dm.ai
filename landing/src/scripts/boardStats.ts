// Pure board-stats helpers for the /proto/ factory board.
// Everything here must stay DOM-free so vitest can run it headless.

export type TokenRow = {
  leg?: string | null;
  at?: string | null;
  prompt?: number | null;
  completion?: number | null;
  total?: number | null;
  model?: string | null;
  cacheRead?: number | null;
};

export type HistoryEntry = { state: string; at?: string };

export type StatCard = {
  pr?: number;
  issue?: number;
  title?: string;
  devStartedAt?: string;
  approvedAt?: string;
  prCreated?: string;
  queuePos?: number | null;
  history?: HistoryEntry[];
  tokens?: TokenRow[];
};

/** Lanes that are pure storage/queues — nothing executes inside them. */
export const WAITING_LANES = ['approved_queue', 'queued', 'blocked', 'inbox', 'merged_recent'];

/** A lane counts as active when a card entered it no longer ago than this. */
export const ACTIVE_WINDOW_MS = 30 * 60 * 1000;

export type TokenTotals = {
  /** Input tokens actually sent to models: Σ prompt + cacheRead. */
  read: number;
  /** Output tokens generated by models: Σ completion. */
  write: number;
  /** Rows that carry only `total` (degraded producer) — cannot be split. */
  unsplit: number;
  /** Number of token rows aggregated. */
  legs: number;
};

/**
 * Aggregate read/write token spend across cards.
 *
 * A row is read = prompt + cacheRead, write = completion (the producer's
 * contract). A row with neither prompt nor completion but a total cannot be
 * split — it lands in `unsplit`, never silently inside read.
 */
export function tokenTotals(cards: StatCard[]): TokenTotals {
  return sumTokenRows(cards.flatMap((c) => c.tokens ?? []));
}

/** Aggregate raw token rows (camelCase wins, snake_case falls back). */
export function sumTokenRows(rows: TokenRow[]): TokenTotals {
  const out: TokenTotals = { read: 0, write: 0, unsplit: 0, legs: 0 };
  for (const t of rows) {
    out.legs += 1;
    const prompt = typeof t.prompt === 'number' ? t.prompt : null;
    const completion = typeof t.completion === 'number' ? t.completion : null;
    const cacheRaw = t.cacheRead == null ? (t as { cache_read?: unknown }).cache_read : t.cacheRead;
    const cacheRead = typeof cacheRaw === 'number' ? cacheRaw : typeof cacheRaw === 'string' && cacheRaw !== '' && !Number.isNaN(+cacheRaw) ? +cacheRaw : 0;
    if (prompt == null && completion == null) {
      out.unsplit += typeof t.total === 'number' ? t.total : 0;
      continue;
    }
    out.read += (prompt ?? 0) + cacheRead;
    out.write += completion ?? 0;
  }
  return out;
}

/**
 * Sum a whole published tokens stream ({'pr-N': rows, 'issue-N': rows}).
 * A null/absent stream (the factory publishes none) yields null — callers
 * render an honest dash instead of a lying zero.
 */
export function sumTokensMap(map: Record<string, TokenRow[]> | null): TokenTotals | null {
  if (!map || typeof map !== 'object') return null;
  const rows = Object.values(map).flatMap((r) => (Array.isArray(r) ? r : []));
  return sumTokenRows(rows);
}

/** total_count from a GitHub search response, or null on any miss. */
export function searchCount(json: unknown): number | null {
  if (!json || typeof json !== 'object') return null;
  const n = (json as { total_count?: unknown }).total_count;
  return typeof n === 'number' && n >= 0 ? n : null;
}

/** Searchable factory picker: substring over id+name, case-insensitive. */
export function filterFactories<T extends { id: string; name: string }>(list: readonly T[], q: string): T[] {
  const query = q.trim().toLowerCase();
  if (!query) return [...list];
  return list.filter((f) => f.id.toLowerCase().includes(query) || f.name.toLowerCase().includes(query));
}

export type ArchiveRow = { num: number; title: string; at: string | null; leadMs?: number | null };
export type MergedArchive = { total: number | null; items: ArchiveRow[] };

/**
 * Parse a GitHub search response (repo is:pr is:merged author:machine) into
 * archive rows for the merged lane: the snapshot holds only 24h of merges,
 * the archive restores the rest. Items keep the API's order (newest first);
 * rows without a number are skipped, list is capped at 50. Any payload that
 * is not a well-formed search response → null (callers render an honest
 * "unavailable", never a fake empty).
 */
export function mergedArchiveFromSearch(json: unknown): MergedArchive | null {
  if (!json || typeof json !== 'object') return null;
  const box = json as { total_count?: unknown; items?: unknown };
  if (!Array.isArray(box.items)) return null;
  const items: ArchiveRow[] = [];
  for (const raw of box.items) {
    if (!raw || typeof raw !== 'object') continue;
    const it = raw as { number?: unknown; title?: unknown; closed_at?: unknown; created_at?: unknown };
    if (typeof it.number !== 'number') continue;
    if (items.length >= 50) break;
    const at = typeof it.closed_at === 'string' ? it.closed_at : null;
    const created = typeof it.created_at === 'string' ? it.created_at : null;
    const leadMs = at && created ? Date.parse(at) - Date.parse(created) : null;
    items.push({
      num: it.number,
      title: typeof it.title === 'string' ? it.title : '(untitled)',
      at,
      leadMs: leadMs != null && Number.isFinite(leadMs) && leadMs >= 0 ? leadMs : null,
    });
  }
  return { total: searchCount(json), items };
}

/** Latest timestamp we can attribute to a card, or null. */
export function cardLastStamp(c: StatCard): string | null {
  const h = c.history ?? [];
  const stamps = [c.devStartedAt, c.approvedAt, h.length ? h[h.length - 1].at : undefined, c.prCreated];
  const found = stamps.filter((s): s is string => typeof s === 'string' && !Number.isNaN(Date.parse(s)));
  if (!found.length) return null;
  return found.sort((a, b) => Date.parse(b) - Date.parse(a))[0];
}

function enteredRecently(c: StatCard, nowMs: number, windowMs: number): boolean {
  const at = cardLastStamp(c);
  if (!at) return false;
  const age = nowMs - Date.parse(at);
  return age >= 0 && age <= windowMs;
}

/**
 * Does anything actually happen in this lane right now?
 *
 * - Storage lanes (WAITING_LANES) are queues: cards sit and wait, never active.
 * - validating is active whenever non-empty: by the machine's own semantics a
 *   card only sits there while the mutex CI run is in flight.
 * - Work lanes (development, pr_created, pr_validation, review) are active
 *   only when some card entered within ACTIVE_WINDOW_MS of the snapshot tick —
 *   a PR parked in a lane for two days is data at rest, not activity.
 */
export function laneActive(laneId: string, cards: StatCard[], tickAtMs: number): boolean {
  if (!cards.length) return false;
  if (WAITING_LANES.includes(laneId)) return false;
  if (laneId === 'validating') return true;
  return cards.some((c) => enteredRecently(c, tickAtMs, ACTIVE_WINDOW_MS));
}

export type QueueWait = { depth: number; headAgeMs: number };

/**
 * How long has the head of a waiting lane been queued?
 *
 * - approved_queue: head is the card with queuePos 1 (FIFO the mutex arms),
 *   wait measured from approvedAt (else latest history stamp).
 * - backlog queued: head is the first card (issues sort ascending), wait
 *   measured from the latest history stamp.
 * Returns null when the lane is not a waiting lane, is empty, or carries no
 * usable timestamp (honest unknown).
 */
export function queueWait(laneId: string, cards: StatCard[], tickAtMs: number): QueueWait | null {
  if (!cards.length) return null;
  let head: StatCard | undefined;
  let stamps: (string | null | undefined)[];
  if (laneId === 'approved_queue') {
    head = cards.find((c) => c.queuePos === 1) ?? cards[0];
    stamps = [head.approvedAt, cardLastStamp(head)] as (string | null | undefined)[];
  } else if (laneId === 'queued') {
    head = cards[0];
    stamps = [cardLastStamp(head)] as (string | null | undefined)[];
  } else {
    return null;
  }
  const at = stamps.find((s): s is string => typeof s === 'string' && !Number.isNaN(Date.parse(s)));
  if (!at) return null;
  const age = tickAtMs - Date.parse(at);
  if (age < 0) return null;
  return { depth: cards.length, headAgeMs: age };
}

/** Repeat a GitHub search qualifier per value (repeated kind = OR). */
export function qualifyAll(field: string, values: readonly string[]): string {
  return values.map((v) => `${field}:${v}`).join(' ');
}

/* ---------------- phase flow analytics (lane/ticket modals) ---------------- */

export type HistSpan = { state: string; startMs: number; endMs: number; durMs: number };

/** Split a card history into sequential time spans; the last span ends at endAt (merged) or nowMs. */
export function histSpans(history: HistoryEntry[], nowMs: number, endAt?: string | null): HistSpan[] {
  const spans: HistSpan[] = [];
  let prev: { state: string; atMs: number } | null = null;
  const end = endAt ? Date.parse(endAt) : nowMs;
  for (const e of history) {
    if (!e.at) continue;
    const atMs = Date.parse(e.at);
    if (Number.isNaN(atMs)) continue;
    if (prev) spans.push({ state: prev.state, startMs: prev.atMs, endMs: atMs, durMs: Math.max(0, atMs - prev.atMs) });
    prev = { state: e.state, atMs };
  }
  if (prev && Number.isFinite(end)) {
    spans.push({ state: prev.state, startMs: prev.atMs, endMs: end, durMs: Math.max(0, end - prev.atMs) });
  }
  return spans;
}

export type PhaseAg = { state: string; visits: number; totalMs: number; avgMs: number; maxMs: number };

/** Group spans per state: visit count, total/avg/max dwell — sorted by total desc. */
export function phaseAggregate(spans: HistSpan[]): PhaseAg[] {
  const by = new Map<string, { visits: number; totalMs: number; maxMs: number }>();
  for (const s of spans) {
    const cur = by.get(s.state) ?? { visits: 0, totalMs: 0, maxMs: 0 };
    cur.visits += 1;
    cur.totalMs += s.durMs;
    cur.maxMs = Math.max(cur.maxMs, s.durMs);
    by.set(s.state, cur);
  }
  return [...by.entries()]
    .map(([state, v]) => ({ state, ...v, avgMs: v.totalMs / v.visits }))
    .sort((a, b) => b.totalMs - a.totalMs);
}

export function medianMs(values: number[]): number {
  if (!values.length) return 0;
  const s = [...values].sort((a, b) => a - b);
  const mid = Math.floor(s.length / 2);
  return s.length % 2 ? s[mid] : (s[mid - 1] + s[mid]) / 2;
}

export type LaneDwell = {
  /** Cards whose history touches the lane. */
  n: number;
  avgMs: number; medianMs: number; maxMs: number;
  /** For merged cards: first history entry → mergedAt. */
  lead?: { n: number; avgMs: number; medianMs: number };
};

/** How long cards spend in one lane, across a set of snapshot cards. */
export function laneDwell(cards: { history?: HistoryEntry[]; mergedAt?: string }[], lane: string, nowMs: number): LaneDwell {
  const dwells: number[] = [];
  const leads: number[] = [];
  for (const c of cards) {
    const spans = histSpans(c.history ?? [], nowMs, c.mergedAt);
    if (!spans.length) continue;
    const inLane = spans.filter((s) => s.state === lane).reduce((acc, s) => acc + s.durMs, 0);
    dwells.push(inLane);
    if (c.mergedAt && spans[0]) leads.push(spans[0].startMs >= 0 ? Date.parse(c.mergedAt) - spans[0].startMs : 0);
  }
  const touched = dwells.filter((d) => d > 0);
  const avg = (arr: number[]) => (arr.length ? arr.reduce((a, b) => a + b, 0) / arr.length : 0);
  const out: LaneDwell = {
    n: touched.length,
    avgMs: avg(touched),
    medianMs: medianMs(touched),
    maxMs: touched.length ? Math.max(...touched) : 0,
  };
  if (leads.length) out.lead = { n: leads.length, avgMs: avg(leads), medianMs: medianMs(leads) };
  return out;
}

/** Key of a card in the factory tokens stream (pr-<N> / issue-<N>). */
export function tokensKey(card: { pr?: number; issue?: number }): string | null {
  if (card.pr != null) return 'pr-' + card.pr;
  if (card.issue != null) return 'issue-' + card.issue;
  return null;
}

/** Card tokens from the factory tokens stream; falls back to tokens embedded in the snapshot. */
export function tokensFor(
  card: { pr?: number; issue?: number; tokens?: TokenRow[] },
  stream?: Record<string, TokenRow[]> | null,
): TokenRow[] {
  const k = tokensKey(card);
  if (stream && k && stream[k]) return stream[k];
  return card.tokens ?? [];
}

/** Merges per UTC day over the last `days` days, zero-filled, oldest first ('MM-DD'). */
export function mergesPerDay(items: { at: string | null }[], days: number, nowMs: number): { date: string; n: number }[] {
  const out: { date: string; n: number }[] = [];
  const counts = new Map<string, number>();
  for (const it of items) {
    if (!it.at) continue;
    const t = Date.parse(it.at);
    if (!Number.isFinite(t)) continue;
    const key = new Date(t).toISOString().slice(5, 10);
    counts.set(key, (counts.get(key) ?? 0) + 1);
  }
  for (let i = days - 1; i >= 0; i--) {
    const key = new Date(nowMs - i * 86400000).toISOString().slice(5, 10);
    out.push({ date: key, n: counts.get(key) ?? 0 });
  }
  return out;
}

/** Day-level throughput stats for the archive window. */
export function mergeDayStats(items: { at: string | null }[], days: number, nowMs: number): { total: number; perDay: number; best: { date: string; n: number } | null } {
  const per = mergesPerDay(items, days, nowMs);
  const total = per.reduce((a, d) => a + d.n, 0);
  const best = per.reduce<{ date: string; n: number } | null>((b, d) => (!b || d.n > b.n ? { date: d.date, n: d.n } : b), null);
  return { total, perDay: total / days, best: best && best.n > 0 ? best : null };
}
