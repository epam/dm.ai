import { Document, isAlias, isMap, isScalar, isSeq, parseDocument, YAMLSeq } from 'yaml';

export const GITLAB_QUALITY_FILE = '.dmtools-factory-quality.yml';
export const GITLAB_QUALITY_MARKER = '# Generated by DMTools factory setup.';
export const GITLAB_SCHEDULE_VARIABLE = 'DMTOOLS_FACTORY_SCHEDULE';
export const GITLAB_TOOLCHAIN_JOB = '.dmtools-teammate-toolchains';
export const GITLAB_MERGE_JOB = 'dmtools-factory-merge';
const GITLAB_TEAMMATE_MARKER = '# Teammate lifecycle, token selection, queue scanning and label automation come from the shared template.';

export interface GitlabCiSnapshot {
  repo: string;
  baseUrl: string;
  path: string;
  ref: string;
  revision: string;
  content: string | null;
  mergedYaml: string | null;
  qualityContent: string | null;
  teammateContent: string | null;
  fileVersions: Record<string, string>;
}

function pipelineDocument(content: string, label: string) {
  const doc = parseDocument(content, { merge: true });
  if (doc.errors.length || !isMap(doc.contents)) {
    throw new Error(`${label} must be a valid GitLab CI YAML mapping: ${doc.errors[0]?.message ?? 'mapping expected'}`);
  }
  const unsupported = doc.warnings.find((warning) => !warning.message.startsWith('Unresolved tag: !reference'));
  if (unsupported) throw new Error(`${label} cannot be safely updated: ${unsupported.message}`);
  return doc;
}

export function gitlabPipelineStage(snapshot?: GitlabCiSnapshot): string {
  if (!snapshot?.content) return 'test';
  if (!snapshot.mergedYaml) throw new Error('GitLab did not return the merged CI configuration.');
  const merged = pipelineDocument(snapshot.mergedYaml, 'Merged GitLab CI configuration');
  const stages = merged.get('stages', true);
  if (stages === undefined) return 'test';
  if (!isSeq(stages)) throw new Error('GitLab CI stages must be a list.');

  const findStage = (items: unknown[]): string | undefined => {
    for (const item of items) {
      if (isSeq(item)) {
        const nested = findStage(item.items);
        if (nested) return nested;
      } else if (isScalar(item) && typeof item.value === 'string' && !item.value.startsWith('.')) {
        return item.value;
      }
    }
    return undefined;
  };
  const stage = findStage(stages.items);
  if (!stage) throw new Error('GitLab CI needs at least one regular stage for the factory jobs.');
  return stage;
}

function localInclude(item: unknown): string | undefined {
  if (isScalar(item) && typeof item.value === 'string') return item.value.replace(/^\.?\//, '');
  if (isMap(item)) {
    const local = item.get('local');
    return typeof local === 'string' ? local.replace(/^\.?\//, '') : undefined;
  }
  return undefined;
}

function remoteInclude(item: unknown): string | undefined {
  if (!isMap(item)) return undefined;
  const remote = item.get('remote');
  return typeof remote === 'string' ? remote : undefined;
}

function isFactorySmInclude(item: unknown): boolean {
  const remote = remoteInclude(item);
  return Boolean(remote && /^https:\/\/raw\.githubusercontent\.com\/IstiN\/dmtools-agentic-workflows\/[^/]+\/gitlab\/factory-sm\.yml$/.test(remote));
}

function mergeMap(target: unknown, source: unknown, label: string) {
  if (!isMap(target) || !isMap(source)) throw new Error(`${label} must be a YAML mapping.`);
  for (const pair of source.items) {
    const key = isScalar(pair.key) ? pair.key.value : pair.key;
    if (typeof key !== 'string') throw new Error(`${label} has an unsupported key.`);
    const previous = target.get(key, true);
    if (key === 'variables' && isMap(previous) && isMap(pair.value)) {
      mergeMap(previous, pair.value, `${label} variables`);
    } else {
      target.set(key, pair.value);
    }
  }
}

function addFactoryIncludes(
  doc: ReturnType<typeof pipelineDocument>,
  factory: ReturnType<typeof pipelineDocument>,
  quality: boolean,
  managed: boolean,
) {
  const current = doc.get('include', true);
  if (isAlias(current)) throw new Error('GitLab CI include aliases cannot be updated safely.');
  const includes = isSeq(current) ? current : new YAMLSeq(doc.schema);
  if (current !== undefined && !isSeq(current)) includes.add(current);
  const factoryIncludes = factory.get('include', true);
  if (!isSeq(factoryIncludes)) throw new Error('Factory template is missing its GitLab includes.');
  const expectedRemote = factoryIncludes.items.map(remoteInclude).find(Boolean);

  includes.items = includes.items.filter((item) => {
    const local = localInclude(item);
    if (local === 'ai-teammate.yml' && isMap(item) && item.items.length !== 1) {
      throw new Error('The existing ai-teammate.yml include has custom options and cannot be updated safely.');
    }
    if (local === GITLAB_QUALITY_FILE) {
      if (isMap(item) && item.items.length !== 1) {
        throw new Error(`The existing ${GITLAB_QUALITY_FILE} include has custom options and cannot be replaced safely.`);
      }
      return false;
    }
    const remote = remoteInclude(item);
    if (!isFactorySmInclude(item)) return true;
    if (isMap(item) && item.items.length !== 1) {
      throw new Error('The existing GitLab factory include has custom options and cannot be replaced safely.');
    }
    if (!managed && remote !== expectedRemote) {
      throw new Error('The existing GitLab CI includes a different factory-sm version that cannot be updated safely.');
    }
    return false;
  });
  for (const item of factoryIncludes.items) {
    const local = localInclude(item);
    const remote = remoteInclude(item);
    if (!includes.items.some((entry) => (local && localInclude(entry) === local) || (remote && remoteInclude(entry) === remote))) {
      includes.add(item);
    }
  }
  if (quality) includes.add(doc.createNode({ local: GITLAB_QUALITY_FILE }));
  doc.set('include', includes);
}

function addWorkflowRules(
  doc: ReturnType<typeof pipelineDocument>,
  factory: ReturnType<typeof pipelineDocument>,
  snapshot: GitlabCiSnapshot | undefined,
  quality: boolean,
) {
  const existing = Boolean(snapshot?.content);
  let workflow = doc.get('workflow', true);
  if (existing && workflow === undefined && snapshot?.mergedYaml) {
    const merged = pipelineDocument(snapshot.mergedYaml, 'Merged GitLab CI configuration');
    const inherited = merged.get('workflow', true);
    if (inherited !== undefined) {
      if (!isMap(inherited)) throw new Error('Inherited GitLab workflow must be a YAML mapping.');
      const includes = doc.get('include', true);
      const entries = isSeq(includes) ? includes.items : includes === undefined ? [] : [includes];
      if (entries.some((entry) => isMap(entry) && entry.has('rules'))) {
        throw new Error('An inherited GitLab workflow with conditional includes cannot be updated safely.');
      }
      workflow = inherited.clone();
      doc.set('workflow', workflow);
    }
  }
  if (workflow === undefined) {
    if (!quality) return;
    doc.set('workflow', { rules: [{ if: '$CI_PIPELINE_SOURCE == "merge_request_event"' }, { when: 'always' }] });
    return;
  }
  if (!isMap(workflow)) throw new Error('GitLab workflow must be a YAML mapping.');
  const rules = workflow.get('rules', true);
  if (rules === undefined) {
    if (!quality) return;
    workflow.set('rules', doc.createNode([{ if: '$CI_PIPELINE_SOURCE == "merge_request_event"' }, { when: 'always' }]));
    return;
  }
  if (!isSeq(rules) || rules.tag === '!reference') {
    throw new Error('GitLab workflow rules must be a list that can be safely extended.');
  }
  const factoryRules = factory.getIn(['workflow', 'rules'], true);
  if (!isSeq(factoryRules)) throw new Error('Factory template is missing its GitLab workflow rules.');
  const conditions = factoryRules.items.flatMap((rule) => {
    if (!isMap(rule)) return [];
    const condition = rule.get('if');
    if (typeof condition !== 'string') return [];
    return [condition];
  });
  if (quality) conditions.push('$CI_PIPELINE_SOURCE == "merge_request_event"');
  for (const condition of conditions.reverse()) {
    const index = rules.items.findIndex((rule) =>
      isMap(rule) && rule.items.length === 1 && rule.get('if') === condition);
    const rule = index < 0 ? doc.createNode({ if: condition }) : rules.items.splice(index, 1)[0];
    rules.items.unshift(rule);
  }
}

export function renderGitlabPipeline(
  factoryContent: string,
  snapshot: GitlabCiSnapshot | undefined,
  quality: boolean,
): string {
  const factory = pipelineDocument(factoryContent, 'GitLab factory template');
  const doc = snapshot?.content
    ? pipelineDocument(snapshot.content, 'Existing GitLab CI configuration')
    : pipelineDocument(factoryContent, 'GitLab factory template');
  const existing = Boolean(snapshot?.content);
  const currentJob = doc.get('factory-sm', true);
  const currentIncludes = doc.get('include', true);
  const includeEntries = isSeq(currentIncludes) ? currentIncludes.items : currentIncludes === undefined ? [] : [currentIncludes];
  const managed = isMap(currentJob) && currentJob.get('extends') === '.factory-sm' && includeEntries.some(isFactorySmInclude);
  if (existing && currentJob !== undefined && !managed) {
    throw new Error('The existing GitLab CI configuration already has an unrelated factory-sm job.');
  }
  if (snapshot && snapshot.teammateContent !== null && !snapshot.teammateContent.startsWith(GITLAB_TEAMMATE_MARKER)) {
    throw new Error('The existing ai-teammate.yml is not a DMTools factory file and will not be overwritten.');
  }
  if (doc.has(GITLAB_TOOLCHAIN_JOB)) {
    throw new Error(`The existing GitLab CI configuration defines ${GITLAB_TOOLCHAIN_JOB}, which is reserved for DMTools agent toolchains.`);
  }
  if (doc.has(GITLAB_MERGE_JOB)) {
    throw new Error(`The existing GitLab CI configuration defines ${GITLAB_MERGE_JOB}, which is reserved for the DMTools merge bot.`);
  }
  const managedQuality = snapshot?.qualityContent?.startsWith(GITLAB_QUALITY_MARKER) ?? false;
  if (quality && snapshot && snapshot.qualityContent !== null && !managedQuality) {
    throw new Error(`The existing ${GITLAB_QUALITY_FILE} is not a DMTools factory file and will not be overwritten.`);
  }
  if (snapshot?.content && snapshot.mergedYaml) {
    const merged = pipelineDocument(snapshot.mergedYaml, 'Merged GitLab CI configuration');
    const inheritedFactory = merged.get('factory-sm', true);
    if (currentJob === undefined && inheritedFactory !== undefined) {
      throw new Error('The existing GitLab CI includes a factory-sm job that cannot be updated safely.');
    }
    if (!managed && doc.get('ai-teammate-scan', true) === undefined && merged.has('ai-teammate-scan')) {
      throw new Error('The existing GitLab CI includes an ai-teammate-scan job that cannot be updated safely.');
    }
    if (!managed && (
      merged.has('ai-teammate') ||
      merged.has('ai-teammate-auto') ||
      merged.has(GITLAB_TOOLCHAIN_JOB) ||
      merged.has(GITLAB_MERGE_JOB) ||
      (isMap(merged.contents) && merged.contents.items.some((pair) => {
        const key = isScalar(pair.key) ? pair.key.value : pair.key;
        return typeof key === 'string' && /^\.factory-(sm|teammate)(-|$)/.test(key);
      }))
    )) {
      throw new Error('The existing GitLab CI includes teammate or factory parent jobs that cannot be updated safely.');
    }
    const existingVariables = merged.get('variables', true);
    const factoryVariables = factory.get('variables', true);
    if (isMap(existingVariables) && existingVariables.has(GITLAB_SCHEDULE_VARIABLE)) {
      throw new Error(`The existing GitLab CI variable ${GITLAB_SCHEDULE_VARIABLE} is reserved for the DMTools factory schedule.`);
    }
    if (!managed && isMap(existingVariables) && isMap(factoryVariables)) {
      for (const pair of factoryVariables.items) {
        const key = isScalar(pair.key) ? pair.key.value : pair.key;
        if (typeof key === 'string' && existingVariables.has(key)) {
          throw new Error(`The existing GitLab CI variable ${key} is reserved for the DMTools factory.`);
        }
      }
    }
    if (quality && (doc.has('dmtools-quality') || (merged.has('dmtools-quality') && !managedQuality))) {
      throw new Error('The existing GitLab CI configuration already has an unrelated dmtools-quality job.');
    }
    const includes = doc.get('include', true);
    const entries = isSeq(includes) ? includes.items : includes === undefined ? [] : [includes];
    if (entries.some((item) => localInclude(item) === GITLAB_QUALITY_FILE) && !managedQuality) {
      throw new Error(`The existing ${GITLAB_QUALITY_FILE} include is not managed by DMTools.`);
    }
  }
  addFactoryIncludes(doc, factory, quality, managed);
  if (existing) {
    let variables = doc.get('variables', true);
    if (variables === undefined) {
      variables = doc.createNode({});
      doc.set('variables', variables);
    }
    const factoryVariables = factory.get('variables', true);
    if (!isMap(variables) || !isMap(factoryVariables)) throw new Error('GitLab CI variables must be a YAML mapping.');
    if (!managed) {
      for (const pair of factoryVariables.items) {
        const key = isScalar(pair.key) ? pair.key.value : pair.key;
        if (typeof key === 'string' && variables.has(key)) {
          throw new Error(`The existing GitLab CI variable ${key} is reserved for the DMTools factory.`);
        }
      }
    }
    mergeMap(variables, factoryVariables, 'GitLab CI variables');
    for (const name of ['factory-sm', 'ai-teammate-scan']) {
      const source = factory.get(name, true);
      const target = doc.get(name, true);
      if (target === undefined) doc.set(name, source);
      else if (name === 'ai-teammate-scan' && !managed) {
        throw new Error('The existing GitLab CI configuration already has an unrelated ai-teammate-scan job.');
      } else {
        mergeMap(target, source, `GitLab ${name} job`);
        // The factory owns runner selection for its jobs, so clearing the tags must clear them here too.
        if (isMap(source) && isMap(target) && !source.has('tags')) target.delete('tags');
      }
    }
  }
  addWorkflowRules(doc, factory, snapshot, quality);
  return doc.toString();
}

export function renderGitlabQualityPipeline(template: string, stage: string, tags: string[] = []): string {
  const source = pipelineDocument(template, 'GitLab quality template');
  const job = source.get('quality', true);
  if (!isMap(job)) throw new Error('GitLab quality template is missing its quality job.');
  job.set('stage', stage);
  job.set('needs', source.createNode([]));
  job.set('allow_failure', false);
  job.set('after_script', source.createNode([]));
  job.set('rules', source.createNode([{ if: '$CI_PIPELINE_SOURCE == "merge_request_event"' }]));
  if (tags.length) job.set('tags', source.createNode(tags));
  else job.delete('tags');
  const output = new Document();
  output.set('dmtools-quality', job);
  return `${GITLAB_QUALITY_MARKER}\n${output.toString()}`;
}
